void Display(int iNo)
{
    int i = 0, j = 0;
    for(i = 1; i <= iNo; i++)
    {
        printf("*\t");
    
    }
    for(j = 1; j <= iNo; j++)
    {
        printf("#\t");
    }


}



///////////////////////////////////////////////////////////////////////////////////////////////////////
//
// Entry Point Function
//
///////////////////////////////////////////////////////////////////////////////////////////////////////


int main()
{
    int iValue = 0;
    printf("Enter Number\n");
    scanf("%d",&iValue);

    Display(iValue);

    

    return EXIT_SUCCESS;
}